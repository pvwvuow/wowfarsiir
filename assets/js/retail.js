  function initTips() {
    var tip = document.getElementById("rt-tip");
    var cur = null;
    function place(x, y) {
      var w = tip.offsetWidth, h = tip.offsetHeight;
      var px = x + 16, py = y + 16;
      if (px + w > window.innerWidth - 8) px = x - w - 16;
      if (py + h > window.innerHeight - 8) py = Math.max(8, y - h - 16);
      tip.style.left = Math.max(8, px) + "px";
      tip.style.top = Math.max(8, py) + "px";
    }
    function show(el, x, y) {
      var html = el.classList.contains("it") ? itemTip(el.getAttribute("data-it")) : spellTip(el.getAttribute("data-sp"));
      if (!html) return;
      cur = el;
      tip.innerHTML = html;
      tip.style.display = "block";
      place(x, y);
    }
    function hide() { cur = null; tip.style.display = "none"; }
    document.addEventListener("mouseover", function (e) {
      var t = e.target.closest ? e.target.closest(".sp,.it") : null;
      if (t && t !== cur) show(t, e.clientX, e.clientY);
    });
    document.addEventListener("mousemove", function (e) { if (cur) place(e.clientX, e.clientY); });
    document.addEventListener("mouseout", function (e) {
      var t = e.target.closest ? e.target.closest(".sp,.it") : null;
      if (t && t === cur && !(e.relatedTarget && t.contains(e.relatedTarget))) hide();
    });
    document.addEventListener("click", function (e) {
      var t = e.target.closest ? e.target.closest(".sp") : null;
      if (t && window.matchMedia && window.matchMedia("(hover: none)").matches) {
        if (cur === t) hide(); else { var r = t.getBoundingClientRect(); show(t, r.left, r.bottom); }
        return;
      }
      var c = e.target.closest ? e.target.closest(".rt-copy") : null;
      if (c) {
        var code = c.getAttribute("data-code") || "";
        var done = function () { var o = c.textContent; c.textContent = "کپی شد ✓"; setTimeout(function () { c.textContent = o; }, 1800); };
        if (navigator.clipboard && navigator.clipboard.writeText) navigator.clipboard.writeText(code).then(done, function () {});
        return;
      }
      if (!t) hide();
    });
    window.addEventListener("scroll", hide, { passive: true });
  }

