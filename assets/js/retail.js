  function rich(s) {
    var out = "", re = /\*\*(.+?)\*\*|\[\[([^\]|]+?)(?:\|([^\]]+))?\]\]|\{\{(\d+)\}\}/g, last = 0, m;
    s = String(s == null ? "" : s);
    while ((m = re.exec(s))) {
      out += esc(s.slice(last, m.index));
      if (m[1] != null) out += "<b>" + rich(m[1]) + "</b>";
      else if (m[2]) out += spellChip(m[2].trim(), m[3]);
      else out += itemChip(m[4]);
      last = re.lastIndex;
    }
    return out + esc(s.slice(last));
  }

