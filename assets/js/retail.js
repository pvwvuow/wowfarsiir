  /* ---------- spell text cleaner (ported from talents.js: same rules, same chips) ---------- */
  var PH = "\u0001";
  function findClose(s, i) {
    var depth = 0;
    for (var j = i; j < s.length; j++) {
      var c = s[j];
      if (c === "[") depth++;
      else if (c === "]") { depth--; if (depth === 0) return j; }
    }
    return -1;
  }
  function evalTerm(term, specNo) {
    var neg = term.indexOf("!") === 0;
    var body = neg ? term.slice(1) : term;
    var val = false;
    var m = /^c(\d)$/.exec(body);
    if (m) val = Number(m[1]) === specNo;
    return neg ? !val : val;
  }
  function evalCond(cond, specNo) {
    return cond.split("|").some(function (alt) {
      return alt.split("&").every(function (t) { return evalTerm(t.replace(/^\?/, ""), specNo); });
    });
  }
  function resolveConds(s, specNo) {
    var guard = 0;
    while (guard++ < 300) {
      var at = s.indexOf("$?");
      if (at < 0) break;
      var i = at + 2, chosen = null, ok = true, end = i;
      for (;;) {
        var cm = /^((?:!?[a-zA-Z]*\d*)(?:[&|]\??!?[a-zA-Z]*\d*)*)\[/.exec(s.slice(i));
        if (!cm) { ok = false; break; }
        var open = i + cm[1].length;
        var close = findClose(s, open);
        if (close < 0) { ok = false; break; }
        if (chosen === null && evalCond(cm[1], specNo)) chosen = s.slice(open + 1, close);
        i = close + 1;
        if (s[i] === "?") { i += 1; continue; }
        var ws = /^\s*(?=\[)/.exec(s.slice(i));
        if (ws) {
          var bo = i + ws[0].length;
          var c2 = findClose(s, bo);
          if (c2 < 0) { ok = false; break; }
          if (chosen === null) chosen = s.slice(bo + 1, c2);
          i = c2 + 1;
        }
        end = i;
        break;
      }
      if (!ok) { s = s.slice(0, at) + s.slice(at + 2); continue; }
      s = s.slice(0, at) + (chosen == null ? "" : chosen) + s.slice(end);
    }
    return s;
  }
  function replaceBraces(s) {
    var out = "";
    for (var i = 0; i < s.length; i++) {
      if (s[i] === "$" && s[i + 1] === "{") {
        var depth = 0, j = i + 1;
        for (; j < s.length; j++) {
          if (s[j] === "{") depth++;
          else if (s[j] === "}") { depth--; if (depth === 0) break; }
        }
        out += PH;
        i = j;
      } else out += s[i];
    }
    return out;
  }
